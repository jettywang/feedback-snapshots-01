"""
Deployment verification: compare the installed environment against a
deployment lockfile, and decide for each locked package whether the
installed distribution is the exact same build, a rebuild with matching
name and version but no recorded evidence, or a different build entirely.

This exists because internal dependency tooling sometimes rebuilds a wheel
under an identical name and version. Version-only checks (including the
vulnerability audit itself) cannot tell those builds apart, so deployment
verification fingerprints the installed artifacts instead.
"""

from __future__ import annotations

import enum
import hashlib
import logging
from collections.abc import Iterable, Iterator, Sequence
from dataclasses import dataclass
from importlib.metadata import Distribution, distributions
from pathlib import Path
from typing import Any, cast

from packaging.utils import canonicalize_name
from packaging.version import InvalidVersion, Version

logger = logging.getLogger(__name__)

_FINGERPRINT_ALGORITHM = "sha256"


@enum.unique
class VerifyVerdict(str, enum.Enum):
    """
    The per-package outcome of a deployment verification.
    """

    SameBuild = "same-build"
    """
    The installed distribution's fingerprint matches the lockfile: same build.
    """

    PendingEvidence = "pending-evidence"
    """
    Name and version match, but the lockfile records no artifact evidence.
    """

    BuildMismatch = "build-mismatch"
    """
    Name and version match, but the installed artifact is a different build.
    """

    VersionMismatch = "version-mismatch"
    """
    The locked package is installed, but at a different version.
    """

    NotInstalled = "not-installed"
    """
    The locked package is not installed in the environment at all.
    """

    def __str__(self) -> str:
        return self.value


# Verdicts that fail a deployment verification.
FAILING_VERDICTS = frozenset(
    {VerifyVerdict.BuildMismatch, VerifyVerdict.VersionMismatch, VerifyVerdict.NotInstalled}
)


class DeploymentLockError(Exception):
    """
    Raised when a deployment lockfile cannot be parsed.
    """

    pass


def _is_bytecode(path: str) -> bool:
    """
    Check whether a distribution path is generated bytecode.

    Bytecode is compiled at install time and depends on the interpreter,
    not on the build, so it is excluded from artifact fingerprints.
    """
    return "__pycache__" in path or path.endswith((".pyc", ".pyo"))


def fingerprint_distribution(dist: Distribution) -> str:
    """
    Compute a stable fingerprint for an installed distribution.

    The fingerprint is a SHA-256 digest over the distribution's `RECORD`
    entries (sorted, excluding generated bytecode). Two installs of the
    exact same build produce the same fingerprint, while a rebuild under
    the same name and version with different contents does not.

    Distributions without a `RECORD` fall back to hashing the contents of
    their recorded files directly.
    """
    digest = hashlib.sha256()
    record = dist.read_text("RECORD")
    if record is not None:
        lines = sorted(
            line for line in record.splitlines() if line and not _is_bytecode(line.split(",", 1)[0])
        )
        for line in lines:
            digest.update(line.encode())
            digest.update(b"\n")
        return digest.hexdigest()

    files = dist.files
    if files is not None:
        for file in sorted(files, key=str):
            path = str(file)
            if _is_bytecode(path):
                continue
            try:
                # NOTE: `locate_file` returns a `SimplePath`, which typeshed
                # does not guarantee has `read_bytes`; concrete finders do.
                data = cast(Any, dist.locate_file(file)).read_bytes()
            except OSError:
                logger.debug(f"{dist.metadata['Name']}: skipping unreadable file {path}")
                continue
            digest.update(path.encode())
            digest.update(hashlib.sha256(data).digest())
    return digest.hexdigest()


@dataclass(frozen=True)
class InstalledArtifact:
    """
    An installed distribution, reduced to its deployment-relevant identity.
    """

    name: str
    """
    The distribution's name, as recorded in its metadata.
    """

    version: Version
    """
    The distribution's version.
    """

    fingerprint: str
    """
    The distribution's artifact fingerprint; see `fingerprint_distribution`.
    """

    @property
    def canonical_name(self) -> str:
        """
        The artifact's PEP-503 canonicalized name.
        """
        return canonicalize_name(self.name)


def collect_installed(paths: Sequence[Path] | None = None) -> Iterator[InstalledArtifact]:
    """
    Collect the artifacts installed in the current environment, or in the
    given installation paths if supplied.

    Distributions with invalid versions are skipped with a warning, since
    they cannot be meaningfully compared against a lockfile.
    """
    if paths:
        found = distributions(path=[str(path) for path in paths])
    else:
        found = distributions()
    for dist in found:
        name = dist.metadata["Name"]
        if not name:
            logger.debug("skipping distribution with no name in metadata")
            continue
        try:
            version = Version(dist.version)
        except InvalidVersion:
            logger.warning(f"{name}: skipping distribution with invalid version {dist.version}")
            continue
        yield InstalledArtifact(
            name=name, version=version, fingerprint=fingerprint_distribution(dist)
        )


@dataclass(frozen=True)
class LockedArtifact:
    """
    A single `name==version` entry in a deployment lockfile, along with any
    recorded artifact fingerprints ("evidence") for that entry.
    """

    name: str
    """
    The locked package's name.
    """

    version: Version
    """
    The locked package's version.
    """

    hashes: tuple[str, ...] = ()
    """
    Acceptable SHA-256 artifact fingerprints for this package. An empty
    tuple means the lockfile records no evidence for the package.
    """

    @property
    def canonical_name(self) -> str:
        """
        The artifact's PEP-503 canonicalized name.
        """
        return canonicalize_name(self.name)


def load_deployment_lock(filename: Path) -> list[LockedArtifact]:
    """
    Load a deployment lockfile.

    The lockfile uses a requirements-like syntax: one `name==version` pin
    per line, each optionally followed by one or more `--hash=sha256:<hex>`
    evidence tokens. Blank lines and `#` comments are ignored. Hashes in
    algorithms other than SHA-256 are ignored, since fingerprints are
    always SHA-256.

    Raises a `DeploymentLockError` on malformed input.
    """
    entries = []
    for lineno, raw in enumerate(filename.read_text().splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        tokens = line.split()
        hashes = []
        for token in tokens[1:]:
            if not token.startswith("--hash="):
                raise DeploymentLockError(
                    f"{filename}:{lineno}: unexpected token {token!r}; "
                    "only `--hash=sha256:<digest>` options are supported"
                )
            algorithm, _, digest = token[len("--hash=") :].partition(":")
            if algorithm != _FINGERPRINT_ALGORITHM:
                logger.debug(f"{filename}:{lineno}: ignoring non-sha256 hash {algorithm}")
                continue
            hashes.append(digest)

        name, sep, version = tokens[0].partition("==")
        if not sep:
            raise DeploymentLockError(
                f"{filename}:{lineno}: expected a pinned `name==version` entry, got {tokens[0]!r}"
            )
        try:
            parsed_version = Version(version)
        except InvalidVersion as e:
            raise DeploymentLockError(f"{filename}:{lineno}: invalid version {version!r}") from e
        entries.append(LockedArtifact(name=name, version=parsed_version, hashes=tuple(hashes)))
    return entries


def lock_entries_from_installed(installed: Iterable[InstalledArtifact]) -> list[LockedArtifact]:
    """
    Build deployment lockfile entries from installed artifacts, recording
    each artifact's fingerprint as evidence.
    """
    return [
        LockedArtifact(name=artifact.name, version=artifact.version, hashes=(artifact.fingerprint,))
        for artifact in sorted(installed, key=lambda a: (a.canonical_name, a.version))
    ]


def render_deployment_lock(entries: Iterable[LockedArtifact]) -> str:
    """
    Render deployment lockfile entries in the same requirements-like syntax
    that `load_deployment_lock` accepts.
    """
    lines = []
    for entry in entries:
        line = f"{entry.name}=={entry.version}"
        for digest in entry.hashes:
            line += f" --hash={_FINGERPRINT_ALGORITHM}:{digest}"
        lines.append(line)
    return "\n".join(lines) + "\n"


@dataclass(frozen=True)
class VerifyResult:
    """
    The outcome of verifying one locked package against the environment.
    """

    name: str
    """
    The locked package's name.
    """

    locked_version: Version
    """
    The version recorded in the lockfile.
    """

    installed_version: Version | None
    """
    The version installed in the environment, or `None` if not installed.
    """

    verdict: VerifyVerdict
    """
    The verification verdict for this package.
    """

    expected_hashes: tuple[str, ...] = ()
    """
    The artifact fingerprints recorded in the lockfile, if any.
    """

    actual_fingerprint: str | None = None
    """
    The installed artifact's fingerprint, if the package is installed.
    """


def verify_deployment(
    locked: Iterable[LockedArtifact], installed: Iterable[InstalledArtifact]
) -> list[VerifyResult]:
    """
    Verify each locked package against the installed artifacts.

    Name and version are always reported (so remediation owners can still
    see what is deployed); the verdict additionally classifies the
    artifact-level evidence.
    """
    installed_by_name = {artifact.canonical_name: artifact for artifact in installed}
    results = []
    for entry in locked:
        artifact = installed_by_name.get(entry.canonical_name)
        if artifact is None:
            results.append(
                VerifyResult(
                    name=entry.name,
                    locked_version=entry.version,
                    installed_version=None,
                    verdict=VerifyVerdict.NotInstalled,
                    expected_hashes=entry.hashes,
                )
            )
        elif artifact.version != entry.version:
            results.append(
                VerifyResult(
                    name=entry.name,
                    locked_version=entry.version,
                    installed_version=artifact.version,
                    verdict=VerifyVerdict.VersionMismatch,
                    expected_hashes=entry.hashes,
                    actual_fingerprint=artifact.fingerprint,
                )
            )
        elif not entry.hashes:
            results.append(
                VerifyResult(
                    name=entry.name,
                    locked_version=entry.version,
                    installed_version=artifact.version,
                    verdict=VerifyVerdict.PendingEvidence,
                    actual_fingerprint=artifact.fingerprint,
                )
            )
        elif artifact.fingerprint in entry.hashes:
            results.append(
                VerifyResult(
                    name=entry.name,
                    locked_version=entry.version,
                    installed_version=artifact.version,
                    verdict=VerifyVerdict.SameBuild,
                    expected_hashes=entry.hashes,
                    actual_fingerprint=artifact.fingerprint,
                )
            )
        else:
            results.append(
                VerifyResult(
                    name=entry.name,
                    locked_version=entry.version,
                    installed_version=artifact.version,
                    verdict=VerifyVerdict.BuildMismatch,
                    expected_hashes=entry.hashes,
                    actual_fingerprint=artifact.fingerprint,
                )
            )
    return results


def verification_failed(results: Iterable[VerifyResult]) -> bool:
    """
    Check whether any verification result should fail a deployment gate.

    `pending-evidence` does not fail the gate: the deployed version is
    known-good on paper, and the artifact evidence is still being gathered.
    """
    return any(result.verdict in FAILING_VERDICTS for result in results)


def format_verify_results(results: Sequence[VerifyResult]) -> str:
    """
    Render verification results as a human-readable table.

    Every row shows the locked and installed versions, so remediation
    owners can see what is deployed even when artifact evidence is
    missing or mismatched; evidence details follow on indented lines.
    """
    headers = ("Name", "Locked", "Installed", "Verdict")
    rows = [
        (
            result.name,
            str(result.locked_version),
            str(result.installed_version) if result.installed_version is not None else "-",
            str(result.verdict),
        )
        for result in results
    ]
    widths = [
        max(len(headers[i]), *(len(row[i]) for row in rows)) if rows else len(headers[i])
        for i in range(len(headers))
    ]

    def _row(cells: Sequence[str]) -> str:
        return "  ".join(cell.ljust(width) for cell, width in zip(cells, widths)).rstrip()

    lines = [_row(headers), _row(tuple("-" * width for width in widths))]
    for result, row in zip(results, rows):
        lines.append(_row(row))
        if result.verdict is VerifyVerdict.BuildMismatch:
            expected = ", ".join(
                f"{_FINGERPRINT_ALGORITHM}:{digest}" for digest in result.expected_hashes
            )
            lines.append(f"  expected: {expected}")
            lines.append(f"  actual:   {_FINGERPRINT_ALGORITHM}:{result.actual_fingerprint}")
        elif result.verdict is VerifyVerdict.PendingEvidence:
            lines.append(
                f"  no artifact evidence in lockfile; "
                f"installed artifact is {_FINGERPRINT_ALGORITHM}:{result.actual_fingerprint}"
            )
    return "\n".join(lines) + "\n"
