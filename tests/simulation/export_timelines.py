"""Render the three required walks into docs/design/observed-timelines.md.

Run from the repository root:

    .venv/bin/python -m tests.simulation.export_timelines
"""

from __future__ import annotations

import os
from pathlib import Path

import requests

from .pool import ClientPool, DeploymentLease
from .vault_sim import FakeVault, Fault, render_timeline

OUT = Path("docs/design/observed-timelines.md")


def _run(mode: str, **lease_kw):
    vault = FakeVault(issue_task_cookie=False)
    with vault:
        pool = ClientPool(vault)
        lease = DeploymentLease(pool, vault, **lease_kw)
        if mode == "uncertain":
            vault.inject(
                Fault(
                    stage="task.execute",
                    mode="lost_after_commit",
                    note="gateway lost the response after commit",
                )
            )
        elif mode == "refused":
            vault.inject(
                Fault(
                    stage="task.execute",
                    mode="reject",
                    note="deployment service refused revision rev-42",
                )
            )
        lease.claim()
        try:
            lease.execute()
        except (requests.exceptions.ConnectionError, Exception):
            pass
        if mode == "uncertain":
            lease.pooled.in_flight_error = "deploy/run committed but response lost"
            decision = lease.finish(unresolved_outcome=True)
        else:
            decision = lease.finish()
        evidence = {
            "decision": decision.as_dict(),
            # The document is safe to commit: the per-run token id and accessor
            # are replaced with the simulator's ordinal labels.
            "task": f"task:{lease.task.ordinal:04d}" if lease.task else None,
            "accessor": f"hvsacc-task-{lease.task.ordinal:04d}" if lease.task else None,
            "commits": sorted(vault.commits),
            "records": len(vault.records),
        }
        return vault.rows(), evidence, pool.stats


def _run_boundary(kind: str):
    vault = FakeVault()
    if kind == "cookie":
        vault.issue_task_cookie = True
    if kind == "lying-revoke":
        vault.revoke_is_noop = True
    with vault:
        pool = ClientPool(vault)
        lease = DeploymentLease(pool, vault, idempotency_key=f"deploy-{kind}")
        lease.claim()
        lease.execute()
        decision = lease.finish()
        return (
            vault.rows(),
            decision.as_dict(),
            {"commits": sorted(vault.commits), "pool": pool.stats},
        )


def main() -> None:
    sections = []
    for title, mode, kwargs in [
        ("Walk 1: identity switch succeeds (reuse)", "happy", {"idempotency_key": "deploy-happy"}),
        ("Walk 2: service refuses the deployment (reuse)", "refused", {"idempotency_key": "deploy-refused"}),
        ("Walk 3: response uncertain after commit (discard)", "uncertain", {"idempotency_key": "deploy-uncertain"}),
    ]:
        rows, evidence, stats = _run(mode, **kwargs)
        sections.append(render_timeline(rows, title))
        sections.append("")
        sections.append("Decision: `" + evidence["decision"]["action"] + "` — " + evidence["decision"]["reason"])
        sections.append("")
        sections.append(
            "Evidence: task=`{task}`, accessor=`{acc}`, commits={commits}, pool={pool}".format(
                task=evidence["task"],
                acc=evidence["accessor"],
                commits=evidence["commits"],
                pool=stats,
            )
        )
        sections.append("")

    for title, kind in [
        ("Boundary A: revoke returns success but the token survives (discard)", "lying-revoke"),
        ("Boundary B: credential dies but the session carries a task cookie (isolate)", "cookie"),
    ]:
        rows, decision, extra = _run_boundary(kind)
        sections.append(render_timeline(rows, title))
        sections.append("")
        sections.append("Decision: `" + decision["action"] + "` — " + decision["reason"])
        sections.append("")
        sections.append(f"Evidence: commits={extra['commits']}, pool={extra['pool']}")
        sections.append("")

    header = "# Observed request timelines\n\nGenerated by `.venv/bin/python -m tests.simulation.export_timelines` against the in-process fake Vault. `token sent` is the value of `X-Vault-Token` received by the server; `server resolved` is the identity that token actually mapped to at that moment.\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "\n" + "\n".join(sections) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
