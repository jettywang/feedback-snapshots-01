# Full pipeline: binary program stored inside a Beacon config setting, then recovered.
# ---------------------------------------------------------------------------
def test_recover_from_binary_program_inside_beacon_config():
    program = (
        i32(OP_PRINT)
        + i32(OP_PREPEND) + i32(1)
        + i32(OP_MASK)
        + i32(OP_BASE64)
        + i32(OP_APPEND) + i32(2)
        + i32(OP_TERMINATOR)
    )
    block = make_config_block(program)
    bconfig = BeaconConfig(block)

    # The production parser must decode the exact same steps the strict oracle does.
    strict_steps, _ = strict_parse_recover(program)
    assert bconfig.settings["SETTING_C2_RECOVER"] == strict_steps

    payload = b"AB"
    data = base64.b64encode(payload + b"ZZ")
    body = b"P" + MASK_KEY + xor(data, MASK_KEY)

    # Mirror C2Http: build the transform straight from the parsed config setting.
    transform = HttpDataTransform(
        steps=bconfig.settings["SETTING_C2_RECOVER"], reverse=True, build="output"
    )
    response = HttpResponse(status=200, reason=b"OK", headers={}, body=body)
    assert transform.recover(response).output == payload


# ---------------------------------------------------------------------------
# Mutation tests. Each mutation is located both by step index and by raw config offset.
# ---------------------------------------------------------------------------
def test_valid_chain_recovers_and_locates_every_instruction():
    # The baseline chain that recovers cleanly.
    program = (
        i32(OP_PRINT)
        + i32(OP_MASK)
        + i32(OP_BASE64)
        + i32(OP_APPEND) + i32(2)
        + i32(OP_TERMINATOR)
    )
    block = make_config_block(program)
    value_offset = setting_value_offset(block, int(BeaconSetting.SETTING_C2_RECOVER))

    steps, locations = strict_parse_recover(program)
    assert [name for name, _v in steps] == ["print", "mask", "base64", "append"]

    payload = b"AB"
    data = base64.b64encode(payload + b"ZZ")
    body = MASK_KEY + xor(data, MASK_KEY)
    assert recover_body(steps, body) == payload  # clean recovery

    # Step index -> opcode offset inside the program -> absolute offset in the config block.
    assert [locations[i] for i in range(len(steps))] == [0, 4, 8, 12]
    assert [value_offset + locations[i] for i in range(len(steps))] == [
        value_offset,
        value_offset + 4,
        value_offset + 8,
        value_offset + 12,
    ]

def test_reordered_chain_is_detected_and_faulting_step_is_located():
    # Swap mask and base64 relative to the valid chain: print -> base64 -> mask -> append.
    # The wire body is still built for the *valid* ordering, so the mutated program must fail
    # to recover the payload.
    valid_program = (
        i32(OP_PRINT)
        + i32(OP_MASK)
        + i32(OP_BASE64)
        + i32(OP_APPEND) + i32(2)
        + i32(OP_TERMINATOR)
    )
    mutated_program = (
        i32(OP_PRINT)
        + i32(OP_BASE64)   # base64 now runs before unmasking
        + i32(OP_MASK)
        + i32(OP_APPEND) + i32(2)
        + i32(OP_TERMINATOR)
    )

    payload = b"AB"
    data = base64.b64encode(payload + b"ZZ")
    body = MASK_KEY + xor(data, MASK_KEY)

    valid_steps, _ = strict_parse_recover(valid_program)
    mutated_steps, locations = strict_parse_recover(mutated_program)
    assert recover_body(valid_steps, body) == payload  # control: valid chain works

    mutated, trace = trace_recover(mutated_steps, body)
    # base64 is now fed the raw masked binary (instead of printable base64 text). The first
    # divergent step is "base64" at step index 1, whose opcode lives at program offset 4.
    step_names = [name for name, _b, _a in trace]
    assert step_names == ["print", "base64", "mask", "append"]
    expected_base64_text = base64.b64encode(payload + b"ZZ")
    first_diff = next(
        i for i, (name, _b, after) in enumerate(trace)
        if name == "base64" and after != expected_base64_text
    )
    assert first_diff == 1
    assert locations[first_diff] == 4

    # The mutated program does not raise: base64 swallows the binary blob and the chain then
    # silently returns an empty payload instead of the real data. That is precisely the
    # "malformed input is quietly ignored and still produces a (wrong) result" failure mode.
    assert mutated != payload
    assert recover_body(mutated_steps, body) == b""
    # The strict oracle records where the out-of-order instruction lives, so the divergence can
    # be traced back to the exact config byte rather than guessed.
    assert locations[1] == 4


def test_missing_operand_raises_located_error_instead_of_silent_success():
    # APPEND opcode followed by only 2 of the 4 required operand bytes (truncated program).
    truncated_program = i32(OP_PRINT) + i32(OP_APPEND) + b"\x00\x02"
    block = make_config_block(truncated_program)
    value_offset = setting_value_offset(block, int(BeaconSetting.SETTING_C2_RECOVER))

    # The strict oracle refuses the program and points at the APPEND instruction offset.
    with pytest.raises(MalformedRecoverProgram) as excinfo:
        strict_parse_recover(truncated_program)
    append_program_offset = 4  # print(4) then the append opcode
    assert excinfo.value.offset == append_program_offset
    # The same instruction is addressable as an absolute byte inside the raw config block.
    assert value_offset + append_program_offset == value_offset + 4

    # The production parser does not validate operand width: u32be() of the 2-byte fragment
    # silently yields a length, so a malformed program is accepted as if it were well-formed.
    lenient_steps = parse_recover_binary(truncated_program)
    assert lenient_steps == [("print", True), ("append", 2)]
    # It still "recovers successfully" (no exception), proving the malformed program is not
    # rejected. The strict oracle is the guard that turns this into a hard, located failure.
    assert recover_body(lenient_steps, b"ABZZ") == b"AB"
    with pytest.raises(MalformedRecoverProgram) as strict_exc:
        strict_parse_recover(truncated_program)
    assert strict_exc.value.offset == append_program_offset


def test_unknown_opcode_raises_located_error_instead_of_being_ignored():
    # Opcode 99 does not exist; the production parser logs and skips it, the strict one aborts.
    program = i32(99) + i32(OP_PRINT) + i32(OP_TERMINATOR)
    block = make_config_block(program)
    value_offset = setting_value_offset(block, int(BeaconSetting.SETTING_C2_RECOVER))

    with pytest.raises(MalformedRecoverProgram) as excinfo:
        strict_parse_recover(program)
    assert excinfo.value.offset == 0  # first instruction is the bogus opcode
    assert value_offset + excinfo.value.offset == value_offset

    # Contrast with the lenient production behaviour: the bad instruction vanishes silently.
    assert parse_recover_binary(program) == [("print", True)]


def test_truncated_standalone_opcode_is_rejected():
    # A trailing 3-byte fragment cannot be a complete opcode.
    program = i32(OP_PRINT) + b"\x00\x00\x01"
    with pytest.raises(MalformedRecoverProgram) as excinfo:
        strict_parse_recover(program)
    assert excinfo.value.offset == 4
