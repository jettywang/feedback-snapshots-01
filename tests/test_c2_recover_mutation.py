"""Semantic-driven mutation tests for the Beacon HTTP *recover* program.

These tests deliberately drive the **whole recovery path** instead of only exercising the
Base64 helper:

    binary ``SETTING_C2_RECOVER`` program (as stored in a Beacon config)
        -> :func:`dissect.cobaltstrike.beacon.parse_recover_binary`
        -> :class:`dissect.cobaltstrike.c2.HttpDataTransform` (``reverse=True, build="output"``)
        -> :meth:`HttpDataTransform.recover` against a real :class:`HttpResponse`

A small set of independent, self-contained helpers below describe every recover operation
(``prepend``, ``append``, ``mask``, the encodings and the payload/``print`` load) as short
programs. Every expected intermediate byte string is a hand-written vector computed from the
malleable-C2 semantics, not regenerated by the implementation under test.

Malformed programs (truncated operands, unknown opcodes) must surface a hard, locatable error
through the strict oracle instead of being silently dropped and still yielding a "successful"
recovery.
"""

import base64
import struct

import pytest

from dissect.cobaltstrike.beacon import (
    BeaconConfig,
    BeaconSetting,
    SettingsType,
    TransformStep,
    parse_recover_binary,
)
from dissect.cobaltstrike.c2 import HttpDataTransform, HttpResponse
from dissect.cobaltstrike.utils import netbios_decode, netbios_encode, xor

# ---------------------------------------------------------------------------
# Binary instruction opcodes (big-endian uint32), mirroring Beacon.TransformStep
# ---------------------------------------------------------------------------
OP_APPEND = int(TransformStep.APPEND)       # 1, operand: uint32 length
OP_PREPEND = int(TransformStep.PREPEND)     # 2, operand: uint32 length
OP_BASE64 = int(TransformStep.BASE64)       # 3, no operand
OP_PRINT = int(TransformStep.PRINT)         # 4, no operand (loads HTTP body)
OP_NETBIOS = int(TransformStep.NETBIOS)     # 8, no operand
OP_NETBIOSU = int(TransformStep.NETBIOSU)   # 11, no operand
OP_BASE64URL = int(TransformStep.BASE64URL)  # 13, no operand
OP_MASK = int(TransformStep.MASK)           # 15, no operand
OP_TERMINATOR = 0

# A fixed 4-byte XOR mask so every masked vector is deterministic (real beacons use a random one).
MASK_KEY = b"\xde\xad\xbe\xef"


def i32(value: int) -> bytes:
    return struct.pack(">I", value)


# ---------------------------------------------------------------------------
# Strict, offset-tracking parser used as the *test oracle*.
#
# This intentionally does NOT share code with parse_recover_binary(): it is an independent
# specification of the wire grammar that refuses malformed input and remembers where every
# instruction lived inside the raw program.
# ---------------------------------------------------------------------------
class MalformedRecoverProgram(ValueError):
    """Raised when a recover program cannot be fully decoded.

    ``offset`` is the byte offset (relative to the start of the program) at which the faulting
    instruction or operand begins.
    """

    def __init__(self, message: str, offset: int):
        super().__init__(f"{message} (program offset {offset})")
        self.offset = offset


# opcodes that carry a uint32 length operand
_OPERAND_OPS = frozenset({OP_APPEND, OP_PREPEND})
# opcodes that stand alone
_NO_OPERAND_OPS = frozenset(
    {OP_BASE64, OP_PRINT, OP_NETBIOS, OP_NETBIOSU, OP_BASE64URL, OP_MASK}
)


def strict_parse_recover(program: bytes):
    """Decode a recover program and return ``(steps, locations)``.

    ``steps`` uses the same ``(name, value)`` tuples as :func:`parse_recover_binary`.
    ``locations`` maps the step index to the byte offset of its opcode in ``program``.

    Raises :class:`MalformedRecoverProgram` on a truncated opcode, a truncated length operand
    or an unknown opcode.
    """
    steps = []
    locations = {}
    pos = 0
    size = len(program)
    while pos < size:
        opcode_offset = pos
        if size - pos < 4:
            raise MalformedRecoverProgram("truncated opcode", opcode_offset)
        opcode = int.from_bytes(program[pos : pos + 4], "big")
        pos += 4
        if opcode == OP_TERMINATOR:
            break
        if opcode in _OPERAND_OPS:
            if size - pos < 4:
                raise MalformedRecoverProgram(
                    f"truncated length operand for opcode {opcode}", opcode_offset
                )
            length = int.from_bytes(program[pos : pos + 4], "big")
            pos += 4
            name = TransformStep(opcode).name.lower()
            locations[len(steps)] = opcode_offset
            steps.append((name, length))
        elif opcode in _NO_OPERAND_OPS:
            name = TransformStep(opcode).name.lower()
            locations[len(steps)] = opcode_offset
            steps.append((name, True))
        else:
            raise MalformedRecoverProgram(f"unknown opcode {opcode}", opcode_offset)
    return steps, locations


def trace_recover(steps, body: bytes):
    """Apply the recover steps exactly like ``HttpDataTransform.recover`` and record a trace.

    Returns ``(recovered_payload, trace)`` where ``trace`` is a list of
    ``(step_name, data_before, data_after)`` tuples, one per executed step. This is the
    independent re-implementation the production result is cross-checked against.
    """
    data = b""
    trace = []
    # The binary program already stores steps in recover execution order; HttpDataTransform
    # (reverse=True) applies that order directly after its internal reversal.
    for step, step_val in steps:
        before = data
        if step == "append":
            count = step_val if isinstance(step_val, int) else len(step_val)
            data = data[:-count]
        elif step == "prepend":
            count = step_val if isinstance(step_val, int) else len(step_val)
            data = data[count:]
        elif step == "base64":
            data = base64.b64decode(data + b"==")
        elif step == "base64url":
            data = base64.urlsafe_b64decode(data + b"==")
        elif step == "netbios":
            data = netbios_decode(data.upper())
        elif step == "netbiosu":
            data = netbios_decode(data)
        elif step == "mask":
            data = xor(data[4:], data[:4])
        elif step == "print":
            data = body
        else:  # pragma: no cover - defensive, the strict parser never yields anything else
            raise AssertionError(f"unexpected step {step!r}")
        trace.append((step, before, data))
    return data, trace


def build_transform(steps):
    """Construct the response transform the same way ``C2Http`` does for ``SETTING_C2_RECOVER``.

    A copy is passed in because ``HttpDataTransform`` mutates its ``steps`` argument in place
    when it injects the synthetic ``BUILD`` step.
    """
    return HttpDataTransform(steps=list(steps), reverse=True, build="output")


def recover_body(steps, body: bytes):
    """Run the real production recovery path and return the recovered ``output`` payload."""
    transform = build_transform(steps)
    response = HttpResponse(status=200, reason=b"OK", headers={}, body=body)
    return transform.recover(response).output


def make_config_block(program: bytes) -> bytes:
    """Wrap a recover program in a minimal Beacon config TLV block."""
    header = struct.pack(
        ">HHH", int(BeaconSetting.SETTING_C2_RECOVER), int(SettingsType.TYPE_PTR), len(program)
    )
    return header + program + b"\x00\x00"


def setting_value_offset(block: bytes, target: int) -> int:
    """Return the config-block absolute offset where ``target`` setting's value begins."""
    pos = 0
    while pos < len(block):
        index, _type, length = struct.unpack(">HHH", block[pos : pos + 6])
        if index == 0:
            break
        if index == target:
            return pos + 6
        pos += 6 + length
    raise LookupError(f"setting {target} not found in config block")


