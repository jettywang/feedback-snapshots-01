# Independent short programs describing each single operation, with hand vectors.
# Each program is terminated by an explicit zero opcode, like a real beacon block.
# ---------------------------------------------------------------------------
def test_print_loads_http_body_as_payload():
    # print alone: the recovered payload is exactly the HTTP response body.
    program = i32(OP_PRINT) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    body = b"raw-payload"
    assert recover_body(steps, body) == body


def test_append_trims_trailing_operand_bytes():
    # program: print -> append(3). Wire body carries 3 junk bytes after the payload.
    program = i32(OP_PRINT) + i32(OP_APPEND) + i32(3) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    payload = b"AB"
    body = payload + b"ZZZ"
    recovered, trace = trace_recover(steps, body)

    # hand vector: print yields the whole body, append removes the final 3 bytes.
    assert [(s, after) for s, _b, after in trace] == [
        ("print", b"ABZZZ"),
        ("append", b"AB"),
    ]
    assert recovered == payload
    assert recover_body(steps, body) == payload


def test_prepend_trims_leading_operand_bytes():
    # program: print -> prepend(2). Wire body carries 2 junk bytes before the payload.
    program = i32(OP_PRINT) + i32(OP_PREPEND) + i32(2) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    payload = b"AB"
    body = b"QQ" + payload
    recovered, trace = trace_recover(steps, body)

    assert [(s, after) for s, _b, after in trace] == [
        ("print", b"QQAB"),
        ("prepend", b"AB"),
    ]
    assert recovered == payload
    assert recover_body(steps, body) == payload


def test_mask_strips_key_and_xors_payload():
    # program: print -> mask. Wire body is | 4-byte key | xor(payload, key) |.
    program = i32(OP_PRINT) + i32(OP_MASK) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    payload = b"AB"
    body = MASK_KEY + xor(payload, MASK_KEY)
    assert body.hex() == "deadbeef9fef"  # hand vector

    recovered, trace = trace_recover(steps, body)
    assert [(s, after.hex()) for s, _b, after in trace] == [
        ("print", "deadbeef9fef"),
        ("mask", "4142"),
    ]
    assert recovered == payload
    assert recover_body(steps, body) == payload


def test_base64_encoding_roundtrip():
    # program: print -> base64.
    program = i32(OP_PRINT) + i32(OP_BASE64) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    payload = b"AB"
    body = base64.b64encode(payload)  # hand vector: b"QUI="
    assert body == b"QUI="

    recovered, trace = trace_recover(steps, body)
    assert [(s, after) for s, _b, after in trace] == [
        ("print", b"QUI="),
        ("base64", b"AB"),
    ]
    assert recovered == payload
    assert recover_body(steps, body) == payload


def test_base64url_encoding_roundtrip():
    # program: print -> base64url. Use bytes that differ between standard and urlsafe base64.
    program = i32(OP_PRINT) + i32(OP_BASE64URL) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    payload = b"\xfb\xff"
    body = base64.urlsafe_b64encode(payload)  # hand vector: b"-_8="
    assert body == b"-_8="

    recovered, trace = trace_recover(steps, body)
    assert [(s, after.hex()) for s, _b, after in trace] == [
        ("print", "2d5f383d"),
        ("base64url", "fbff"),
    ]
    assert recovered == payload
    assert recover_body(steps, body) == payload


def test_netbios_and_netbiosu_encoding_roundtrip():
    payload = b"AB"
    encoded = netbios_encode(payload)  # b"EBEC"

    # lower-case netbios: recover uppercases before decoding.
    lower_program = i32(OP_PRINT) + i32(OP_NETBIOS) + i32(OP_TERMINATOR)
    lower_steps, _ = strict_parse_recover(lower_program)
    lower_body = encoded.lower()  # hand vector: b"ebec"
    assert lower_body == b"ebec"
    assert trace_recover(lower_steps, lower_body)[0] == payload
    assert recover_body(lower_steps, lower_body) == payload

    # upper-case netbiosu: decoded as-is.
    upper_program = i32(OP_PRINT) + i32(OP_NETBIOSU) + i32(OP_TERMINATOR)
    upper_steps, _ = strict_parse_recover(upper_program)
    upper_body = encoded.upper()  # hand vector: b"EBEC"
    assert upper_body == b"EBEC"
    assert trace_recover(upper_steps, upper_body)[0] == payload
    assert recover_body(upper_steps, upper_body) == payload


def test_zero_length_prepend_is_noop_but_zero_length_append_wipes_data():
    # Edge case in the slice-based implementation:
    #   prepend(0) -> data[0:]  -> unchanged
    #   append(0)  -> data[:-0] -> data[:0] -> b""  (because -0 == 0)
    # A zero-length *prepend* is therefore a no-op, while a zero-length *append* silently
    # discards every byte. Both are documented here as hand-verified semantics.
    prepend_program = (
        i32(OP_PRINT) + i32(OP_PREPEND) + i32(0) + i32(OP_TERMINATOR)
    )
    prepend_steps, _ = strict_parse_recover(prepend_program)
    body = b"abc"
    recovered, trace = trace_recover(prepend_steps, body)
    assert [after for _s, _b, after in trace] == [body, body]
    assert recovered == body
    assert recover_body(prepend_steps, body) == body

    append_program = (
        i32(OP_PRINT) + i32(OP_APPEND) + i32(0) + i32(OP_TERMINATOR)
    )
    append_steps, _ = strict_parse_recover(append_program)
    recovered, trace = trace_recover(append_steps, body)
    assert [after for _s, _b, after in trace] == [body, b""]
    assert recovered == b""
    # The production recover path exhibits the same silent wipe.
    assert recover_body(append_steps, body) == b""


def test_zero_length_payload_recovers_empty_bytes():
    # print -> base64 on an empty payload: success means output is b"", never garbage.
    program = i32(OP_PRINT) + i32(OP_BASE64) + i32(OP_TERMINATOR)
    steps, _ = strict_parse_recover(program)
    body = base64.b64encode(b"")  # empty body
    assert body == b""
    recovered, trace = trace_recover(steps, body)
    assert recovered == b""
    assert all(after == b"" for _s, _b, after in trace)
    assert recover_body(steps, body) == b""


def test_full_chain_intermediate_bytes_match_hand_vectors():
    # Binary program (recover execution order):
    #   print -> prepend(1) -> mask -> base64 -> append(2)
    program = (
        i32(OP_PRINT)
        + i32(OP_PREPEND) + i32(1)
        + i32(OP_MASK)
        + i32(OP_BASE64)
        + i32(OP_APPEND) + i32(2)
        + i32(OP_TERMINATOR)
    )
    steps, locations = strict_parse_recover(program)

    # Build the on-wire body as the forward inverse of the recover steps.
    payload = b"AB"
    data = payload + b"ZZ"                          # forward append(2)
    data = base64.b64encode(data)                  # forward base64
    data = MASK_KEY + xor(data, MASK_KEY)          # forward mask
    body = b"P" + data                             # forward prepend(1)
    assert body.hex() == "50deadbeef8ff8f48e89ca83d2"  # hand vector

    recovered, trace = trace_recover(steps, body)
    # Every intermediate value is a hand-computed vector.
    assert [(step, after.hex()) for step, _before, after in trace] == [
        ("print", "50deadbeef8ff8f48e89ca83d2"),
        ("prepend", "deadbeef8ff8f48e89ca83d2"),
        ("mask", "51554a6157673d3d"),
        ("base64", "41425a5a"),
        ("append", "4142"),
    ]
    assert recovered == payload

    # The production recovery path must agree with the independent tracer.
    assert recover_body(steps, body) == recovered
    # Every (non-terminator) instruction got a recorded location.
    assert sorted(locations) == list(range(len(steps))) == [0, 1, 2, 3, 4]


