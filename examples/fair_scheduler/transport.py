"""
In-memory transport for two real ``h2`` protocol objects.

Nothing here is mocked at the protocol level: a client and a server
:class:`h2.connection.H2Connection` exchange genuine serialised HTTP/2 frames
through a pair of byte buffers.  This lets the fair-scheduler example run the
real stack (real flow-control windows, real priority and reset frames) without
opening a socket, which keeps the demonstration deterministic and offline.
"""

from __future__ import annotations

from collections import deque

from h2.config import H2Configuration
from h2.connection import H2Connection
from h2.events import (
    DataReceived,
    PriorityUpdated,
    RequestReceived,
    StreamReset,
    WindowUpdated,
)


class Pipe:
    """A one-directional byte FIFO written by one peer, drained by the other."""

    def __init__(self) -> None:
        self._chunks: deque[bytes] = deque()

    def write(self, data: bytes) -> None:
        if data:
            self._chunks.append(data)

    def read(self) -> bytes:
        if not self._chunks:
            return b""
        parts = b"".join(self._chunks)
        self._chunks.clear()
        return parts


class H2Link:
    """
    Two h2 connections wired back to back through :class:`Pipe` objects.

    :meth:`pump` moves every pending frame in both directions exactly once and
    returns the events each side observed.
    """

    def __init__(self, client_settings: dict | None = None) -> None:
        server_config = H2Configuration(client_side=False, header_encoding="utf-8")
        client_config = H2Configuration(client_side=True, header_encoding="utf-8")
        self.server = H2Connection(config=server_config)
        self.client = H2Connection(config=client_config)
        self.c2s = Pipe()
        self.s2c = Pipe()

        self.client.initiate_connection()
        self.server.initiate_connection()
        if client_settings:
            self.client.update_settings(client_settings)
        self.pump()  # preamble + settings handshake

    def pump(self) -> tuple[list, list]:
        server_events: list = []
        client_events: list = []

        outgoing = self.client.data_to_send()
        if outgoing:
            self.c2s.write(outgoing)
        wire = self.c2s.read()
        if wire:
            server_events.extend(self.server.receive_data(wire))

        outgoing = self.server.data_to_send()
        if outgoing:
            self.s2c.write(outgoing)
        wire = self.s2c.read()
        if wire:
            client_events.extend(self.client.receive_data(wire))
        return server_events, client_events


class FairServerHarness:
    """
    Glues a real server-side h2 connection to the fair scheduler.

    Request frames are authenticated against the server directory and forwarded
    to ``on_request`` so the demo can attach a body producer and send response
    headers.  All flow control stays inside h2: the scheduler reads the real
    windows, and WINDOW_UPDATE frames generated by the client travel back over
    the same loopback.  Reset and priority events are forwarded to the
    scheduler.
    """

    def __init__(self, link: H2Link, scheduler, auth_directory, *,
                 auto_ack: bool = True, on_request=None) -> None:
        self.link = link
        self.scheduler = scheduler
        self.auth = auth_directory
        self.auto_ack = auto_ack
        self.on_request = on_request
        # Client DataReceived events awaiting an acknowledgement decision.
        self._pending_client_data: deque = deque()
        self.reset_seen: list[int] = []

    # -- client-side helpers ------------------------------------------------ #
    def open_stream(self, stream_id: int, headers: list[tuple[str, str]],
                    *, end_stream: bool = True) -> list:
        self.link.client.send_headers(stream_id, headers, end_stream=end_stream)
        return self._exchange()

    def set_priority(self, stream_id: int, weight: int, depends_on: int) -> list:
        self.link.client.prioritize(stream_id, weight=weight, depends_on=depends_on)
        return self._exchange()

    def reset(self, stream_id: int) -> list:
        self.link.client.reset_stream(stream_id)
        return self._exchange()

    # -- frame exchange ----------------------------------------------------- #
    def _exchange(self) -> list:
        server_events, client_events = self._pump_with_ack()
        for event in server_events:
            self._on_server_event(event)
        # Handling may have queued more frames (response headers/data).
        server_events2, client_events2 = self._pump_with_ack()
        for event in server_events2:
            self._on_server_event(event)
        return server_events + server_events2

    def _pump_with_ack(self) -> tuple[list, list]:
        server_events, client_events = self.link.pump()
        for event in client_events:
            if isinstance(event, DataReceived):
                if self.auto_ack:
                    self.link.client.acknowledge_received_data(
                        event.flow_controlled_length, event.stream_id
                    )
                    # Flush the resulting WINDOW_UPDATE immediately.
                    self.link.pump()
                else:
                    self._pending_client_data.append(event)
        return server_events, client_events

    def _on_server_event(self, event) -> None:
        if isinstance(event, RequestReceived):
            principal = self.auth.authenticate(event.headers)
            if self.on_request is not None:
                self.on_request(event.stream_id, principal, event.headers)
        elif isinstance(event, PriorityUpdated):
            self.scheduler.note_priority(
                event.stream_id, event.weight, event.depends_on
            )
        elif isinstance(event, StreamReset):
            self.reset_seen.append(event.stream_id)
            self.scheduler.note_reset(event.stream_id)
        elif isinstance(event, WindowUpdated):
            # h2 maintains the windows itself; nothing else to do.
            pass

    # -- selective acknowledgement for the liveness scenario ---------------- #
    def ack_pending(self, keep_alive: set[int]) -> None:
        """Ack only data for the named streams; others keep a zero window."""
        while self._pending_client_data:
            event = self._pending_client_data.popleft()
            if event.stream_id in keep_alive:
                self.link.client.acknowledge_received_data(
                    event.flow_controlled_length, event.stream_id
                )
        self.link.pump()

    def drop_pending_acks(self) -> None:
        """Discard un-acked data events (their windows remain consumed)."""
        self._pending_client_data.clear()

    # -- one scheduler round followed by frame flushing --------------------- #
    def run_round(self) -> int:
        sent = self.scheduler.tick()
        self._exchange()
        return sent
