# Fixed, publicly reproducible vectors for the Netlogon challenge /
# credential exchange. They were derived independently of the RubySMB
# implementation:
#
#   session_key = HMAC-SHA-256(shared_secret, client_challenge || server_challenge)[0, 16]
#   credential  = AES-128-CFB8(key: session_key, iv: 0x00 * 16, data)
#
# The same constants were checked with the `openssl` command line tool
# (`openssl dgst -sha256 -mac HMAC ...` and `openssl enc -aes-128-cfb8 ...`).
# Every value here is a public test constant; none of them is a real secret and
# no live secure channel is involved.
