# frozen-string-literal: true

#
class Roda
  module RodaPlugins
    # The hsts plugin configures a Strict-Transport-Security response header
    # for the application:
    #
    #   plugin :hsts
    #   # Strict-Transport-Security: max-age=63072000; includeSubDomains
    #
    #   plugin :hsts, preload: true
    #   # Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
    #
    #   plugin :hsts, max_age: 31536000, subdomains: false
    #   # Strict-Transport-Security: max-age=31536000
    #
    # = Managed per-site HSTS
    #
    # By default, the header is added to the default response headers and is
    # therefore sent for every response of the application, including plain
    # HTTP responses.  If the application is deployed with both direct TLS
    # connections and TLS terminated by a trusted reverse proxy, and can also
    # receive requests for other, unconfirmed sites, pass the +:hosts+ option
    # to only send the header for the confirmed hosts and verified TLS
    # deployment context:
    #
    #   plugin :hsts, hosts: 'www.example.com'
    #   plugin :hsts, hosts: %w'www.example.com api.example.com'
    #   plugin :hsts, hosts: /\A[-0-9a-f]+\.example\.com\z/
    #
    # In this managed mode, the Strict-Transport-Security header is only sent
    # when both of the following are true:
    #
    # * The request host (port ignored) matches one of the configured hosts.
    #   As with the host_authorization plugin, arrays match if any entry matches,
    #   and other values match using the <tt>===</tt> method, so strings,
    #   regexps, and procs are supported.
    # * The request is made over TLS (<tt>request.ssl?</tt> returns true).
    #   This covers both direct TLS connections (<tt>HTTPS=on</tt>) and TLS
    #   terminated by a trusted proxy that sets the <tt>X-Forwarded-Proto</tt>
    #   or <tt>X-Forwarded-Ssl</tt> header. Plain HTTP requests never receive
    #   the header.
    #
    # Because the header is applied in after processing of the final Rack
    # response, the same policy is used for regular routes and for responses
    # generated by the error_handler plugin. Other Roda applications mounted
    # under this one keep their own default headers, and only emit the managed
    # HSTS header if they configure the plugin with +:hosts+ themselves and the
    # request matches their deployment context.
    module Hsts
      # Ensure default_headers plugin is loaded first
      def self.load_dependencies(app, opts=OPTS)
        app.plugin :default_headers
      end

      # Configure the Strict-Transport-Security header. Keyword arguments:
      # +max_age+ :: Set max-age in seconds (default is 63072000, two years)
      # +preload+ :: Set preload, so the domain can be included in HSTS preload lists
      # +subdomains+ :: Set to +false+ to not set includeSubDomains. By default,
      #                 includeSubDomains is set to enforce HTTPS for subdomains.
      # +hosts+ :: A host string, array of hosts, regexp, or proc identifying the
      #            confirmed sites. When given, HSTS is only sent for matching hosts
      #            on TLS requests, instead of being added to the default headers.
      def self.configure(app, opts=(no_positional_opts = true; OPTS),
          max_age: opts[:max_age]||63072000,
          subdomains: opts.fetch(:subdomains, true),
          preload: opts[:preload],
          hosts: opts[:hosts],
          **kw)
        RodaPlugins.check_keywords("the hsts plugin", no_positional_opts, opts, kw)

        header = "max-age=#{max_age}#{'; includeSubDomains' unless subdomains == false}#{'; preload' if preload}".freeze
        app.opts[:hsts_header] = header

        if hosts
          app.opts[:hsts_hosts] = hosts
        else
          app.plugin :default_headers, RodaResponseHeaders::STRICT_TRANSPORT_SECURITY => header
        end
      end

      module ClassMethods
        RodaPlugins.opt_attr_reader(self, :hsts_hosts)
        RodaPlugins.opt_attr_reader(self, :hsts_header)
      end

      module InstanceMethods
        private

        # Apply the managed HSTS header to the final Rack response only for
        # confirmed hosts on TLS requests. Runs for error handler responses as
        # well, so normal and error routes use the same policy. Responses from
        # other Rack applications mounted with r.run are left untouched, so
        # their own default headers remain in effect.
        def _roda_after_60__hsts(res)
          return unless res
          return unless res[1].equal?(@_response.headers)
          return unless (hosts = self.class.hsts_hosts)
          return unless @_request.ssl? && _hsts_host_authorized?(@_request.host, hosts)

          res[1][RodaResponseHeaders::STRICT_TRANSPORT_SECURITY] ||= self.class.hsts_header
        end

        # Whether the request host is one of the configured HSTS hosts.
        def _hsts_host_authorized?(host, authorized_hosts)
          case authorized_hosts
          when Array
            authorized_hosts.any?{|authorized_host| _hsts_host_authorized?(host, authorized_host)}
          else
            authorized_hosts === host
          end
        end
      end
    end

    register_plugin(:hsts, Hsts)
  end
end
